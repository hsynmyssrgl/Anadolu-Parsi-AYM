import { createHash } from 'node:crypto';

const EXPECTED_METHODS = Object.freeze([
  Object.freeze({
    operation: 'authorize',
    wireMethod: 'policy.authorize',
    payloadType: 'PolicyAuthorizationContractPayload',
    resultType: 'PolicyAuthorizationContractResult'
  }),
  Object.freeze({
    operation: 'verify',
    wireMethod: 'policy.verify',
    payloadType: 'PolicyReceiptVerificationContractPayload',
    resultType: 'PolicyReceiptVerificationContractResult'
  })
]);

export const sha256 = (value) => createHash('sha256').update(value).digest('hex');

export const assertPpk026PolicyClientSchema = (schema) => {
  if (!schema || typeof schema !== 'object' || Array.isArray(schema)) {
    throw new TypeError('PPK-026 policy client schema must be an object');
  }
  if (
    schema.schemaVersion !== 1
    || schema.step !== '32-V'
    || schema.requirement !== 'PPK-026'
    || schema.generatorVersion !== '1.0.0'
    || schema.generatedSource !== 'packages/core-service-client/src/generated-policy-client.ts'
    || schema.generatedManifest !== 'artifacts/manifests/32-V-ppk-026-generated-policy-client.json'
    || schema.transportInterface !== 'GeneratedPolicyClientTransport'
    || schema.clientClass !== 'GeneratedPolicyServiceClient'
  ) {
    throw new Error('PPK-026 policy client schema identity is invalid');
  }
  if (!Array.isArray(schema.methods) || schema.methods.length !== EXPECTED_METHODS.length) {
    throw new Error('PPK-026 policy client schema must contain the exact governed method set');
  }
  for (let index = 0; index < EXPECTED_METHODS.length; index += 1) {
    const actual = schema.methods[index];
    const expected = EXPECTED_METHODS[index];
    if (
      !actual
      || Object.keys(actual).sort().join('|') !== Object.keys(expected).sort().join('|')
      || Object.entries(expected).some(([key, value]) => actual[key] !== value)
    ) {
      throw new Error(`PPK-026 policy client method ${index} is not canonical`);
    }
  }
  const requiredInvariants = [
    'deterministicGeneration',
    'manualGeneratedSourceEditsDenied',
    'unknownPolicyMethodsDenied',
    'rawContractResultsHiddenFromApplications',
    'unobservedPolicyPackageDenied',
    'unobservedClusterFenceDenied',
    'regressingClusterFenceDenied',
    'directProductionPepConstructionDenied'
  ];
  if (
    !schema.invariants
    || Object.keys(schema.invariants).sort().join('|') !== requiredInvariants.sort().join('|')
    || requiredInvariants.some((key) => schema.invariants[key] !== true)
  ) {
    throw new Error('PPK-026 policy client invariants are incomplete');
  }
  return schema;
};

export const renderPpk026GeneratedPolicyClient = (input) => {
  const schema = assertPpk026PolicyClientSchema(input);
  const importedTypes = [...new Set(schema.methods.flatMap((method) => [method.payloadType, method.resultType]))];
  const methodUnion = schema.methods.map((method) => `'${method.wireMethod}'`).join(' | ');
  const methods = schema.methods.map((method) => `  public ${method.operation}(payload: ${method.payloadType}): Promise<${method.resultType}> {
    return this.#transport.request('${method.wireMethod}', payload);
  }`).join('\n\n');
  return `/* eslint-disable */
// This file is generated by scripts/generate-ppk026-policy-client.mjs.
// Manual edits are rejected by the PPK-026 deterministic code-generation gate.
import type {
  CoreServiceMethodPayload,
  CoreServiceMethodResult,
  ${importedTypes.join(',\n  ')}
} from '@ppt/core-service-contracts';

export const GENERATED_POLICY_CLIENT_SCHEMA_VERSION = ${schema.schemaVersion} as const;
export const GENERATED_POLICY_CLIENT_GENERATOR_VERSION = '${schema.generatorVersion}' as const;
export type GeneratedPolicyMethod = ${methodUnion};

export interface ${schema.transportInterface} {
  request<TMethod extends GeneratedPolicyMethod>(
    method: TMethod,
    payload: CoreServiceMethodPayload<TMethod>
  ): Promise<CoreServiceMethodResult<TMethod>>;
}

export class ${schema.clientClass} {
  readonly #transport: ${schema.transportInterface};

  public constructor(transport: ${schema.transportInterface}) {
    if (!transport || typeof transport.request !== 'function') {
      throw new TypeError('Generated policy client transport is unavailable');
    }
    this.#transport = transport;
  }

${methods}
}
`;
};

export const renderPpk026GeneratedPolicyClientManifest = ({ schemaText, source }) => {
  const schema = assertPpk026PolicyClientSchema(JSON.parse(schemaText));
  return `${JSON.stringify({
    schemaVersion: 1,
    step: schema.step,
    requirement: schema.requirement,
    generatorVersion: schema.generatorVersion,
    generationMode: 'deterministic-no-timestamp',
    schemaPath: 'config/32-v-ppk-026-typed-policy-sdk-schema.json',
    schemaSha256: sha256(schemaText),
    generatedSource: schema.generatedSource,
    generatedSourceSha256: sha256(source),
    methodCount: schema.methods.length,
    wireMethods: schema.methods.map((method) => method.wireMethod),
    manualEditsAllowed: false
  }, null, 2)}\n`;
};
