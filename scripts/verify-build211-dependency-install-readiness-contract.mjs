import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createDependencyAcquisitionPlan } from './lib/npm-dependency-acquisition.mjs';
const failures=[];let checks=0;const check=(c,m)=>{checks++;if(!c)failures.push(m)};
const j=async p=>JSON.parse(await readFile(p,'utf8'));
const ledger=await j('config/master-build-ledger.json');
const pkg=await j('package.json');
const policy=await j('config/npm-dependency-acquisition-policy.json');
const lockBytes=await readFile('package-lock.json');
const lock=JSON.parse(lockBytes.toString('utf8'));
const plan=await createDependencyAcquisitionPlan({lock,lockBytes,packageVersion:'1.8.2026-211'});
const currentBuild=Number(String(pkg.version).match(/-(\d+)$/)?.[1] ?? 0);
check(currentBuild>=211,`current build=${currentBuild}`);
check(plan.requiredTarballCount===117,`required=${plan.requiredTarballCount}`);
check(plan.officialRegistryOnly===true,'acquisition plan is not official-registry-only');
check(plan.registry==='https://registry.npmjs.org/','unexpected acquisition registry');
check(policy.officialRegistryOnly===true,'policy officialRegistryOnly is not true');
check(policy.registry==='https://registry.npmjs.org/','policy registry is not official npm');
check(plan.entries.every(x=>x.url.startsWith('https://registry.npmjs.org/')),'plan contains non-official tarball URL');
check(plan.entries.every(x=>typeof x.integrity==='string'&&x.integrity.startsWith('sha512-')),'plan contains missing/non-SHA512 integrity');
check(new Set(plan.entries.map(x=>x.url)).size===plan.entries.length,'plan contains duplicate URLs');
const open2=ledger.remainingWork.find(x=>x.id==='OPEN-002');
check(open2?.status==='OPEN','OPEN-002 must remain OPEN');
check(open2?.order===4,`OPEN-002 order=${open2?.order}`);
check(ledger.remainingWork.find(x=>x.id==='OPEN-021')?.order===2,'OPEN-021 not next Bronze blocker');
check(ledger.remainingWork.find(x=>x.id==='OPEN-022')?.order===3,'OPEN-022 not second Bronze blocker');
const handoff=await readFile('docs/NPM_CLEAN_INSTALL_BUILD211_HANDOFF.md','utf8');
check(handoff.includes('117'),'handoff doc missing 117');
check(handoff.includes('OPEN-002'),'handoff doc missing OPEN-002');
check(handoff.includes('npm ci` PASS')||handoff.includes('npm ci PASS'),'handoff doc does not require real npm ci PASS');
check((await readFile('docs/decisions/DEC-101-clean-install-external-access-handoff.md','utf8')).includes('OPEN-002'),'DEC missing OPEN-002');
check((await readFile('docs/adr/ADR-084-clean-install-external-access-handoff.md','utf8')).includes('fail-closed'),'ADR missing fail-closed');
const out={schemaVersion:2,build:211,currentBuild,scope:'Source-reproducible preservation of Build211 dependency-install fail-closed contract',requiredTarballCount:plan.requiredTarballCount,officialRegistryOnly:true,open002Status:open2?.status??null,cleanInstallPassClaimed:false,checks,status:failures.length?'FAIL':'PASS',failures,generatedAt:new Date().toISOString()};
await mkdir('artifacts/validation',{recursive:true});await writeFile('artifacts/validation/build211-dependency-install-readiness-contract.json',JSON.stringify(out,null,2)+'\n');
if(failures.length){console.error(failures.join('\n'));process.exit(1)}console.log(`Build211 dependency install readiness source contract: PASS ${checks}/${checks}`);
