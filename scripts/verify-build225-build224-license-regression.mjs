import { mkdtemp, mkdir, readFile, writeFile, cp, rm } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createHash } from 'node:crypto';

const report='artifacts/validation/build225-build224-license-regression.json';
const temp=await mkdtemp(join(tmpdir(),'ppt-build225-license-regression-'));
const desktop=join(temp,'desktop');
await mkdir(join(desktop,'scripts'),{recursive:true});
await mkdir(join(desktop,'build'),{recursive:true});
await mkdir(join(desktop,'dist/main'),{recursive:true});
await mkdir(join(desktop,'dist/renderer'),{recursive:true});
await mkdir(join(desktop,'docs'),{recursive:true});
for (const file of ['package.json']) await cp(`apps/desktop/${file}`,join(desktop,file));
for (const file of ['license-rtf-lib.mjs','generate-license-rtf.mjs','verify-license-rtf-sync.mjs','verify-installer.mjs','run-electron-builder.mjs','legacy-upgrade-data-preservation.mjs']) await cp(`apps/desktop/scripts/${file}`,join(desktop,'scripts',file));
for (const file of [
  'LICENSE_TR.rtf','LICENSE_en.rtf','icon.ico','installer.nsh','installer-narration.ps1','extractAppPackage.nsh',
  'installer-bronze-sidebar.bmp','installer-silver-sidebar.bmp','installer-gold-sidebar.bmp'
]) await cp(`apps/desktop/build/${file}`,join(desktop,'build',file));
await cp('apps/desktop/docs/LISANS_TR_KAYNAK.txt',join(desktop,'docs/LISANS_TR_KAYNAK.txt'));
await writeFile(join(desktop,'dist/main/main.mjs'),'x'.repeat(1200));
await writeFile(join(desktop,'dist/main/preload.cjs'),'x'.repeat(1200));
await writeFile(join(desktop,'dist/renderer/index.html'),'<html>'+('x'.repeat(200))+'</html>');
const run=(script)=>spawnSync(process.execPath,[script],{cwd:desktop,encoding:'utf8'});
const checks=[];const add=(id,c,d)=>checks.push({id,status:c?'PASS':'FAIL',...(d===undefined?{}:{details:d})});
let result=run('scripts/verify-license-rtf-sync.mjs');
add('baseline-sync-pass',result.status===0,{stdout:result.stdout.trim(),stderr:result.stderr.trim()});
result=run('scripts/verify-installer.mjs');
add('baseline-installer-verifier-pass',result.status===0,{stdout:result.stdout.trim(),stderr:result.stderr.trim()});
const originalTxt=await readFile(join(desktop,'docs/LISANS_TR_KAYNAK.txt'),'utf8');
await writeFile(join(desktop,'docs/LISANS_TR_KAYNAK.txt'),`${originalTxt.trimEnd()}\nBUILD224_TAMPER_MARKER\n`,'utf8');
result=run('scripts/verify-license-rtf-sync.mjs');
add('txt-tamper-fails',result.status!==0,{stdout:result.stdout.trim(),stderr:result.stderr.trim()});
add('txt-tamper-diagnostic',result.stderr.includes('deterministik üretilmiş güncel içerikle eşleşmiyor'),result.stderr.trim());
result=run('scripts/verify-installer.mjs');
add('installer-detects-txt-tamper',result.status!==0&&result.stderr.includes('UTF-8 lisans kaynağıyla eşleşmiyor'),result.stderr.trim());
result=run('scripts/generate-license-rtf.mjs');
add('explicit-regeneration-pass',result.status===0,{stdout:result.stdout.trim(),stderr:result.stderr.trim()});
result=run('scripts/verify-license-rtf-sync.mjs');
add('post-regeneration-sync-pass',result.status===0,{stdout:result.stdout.trim(),stderr:result.stderr.trim()});
result=run('scripts/verify-installer.mjs');
add('post-regeneration-installer-pass',result.status===0,{stdout:result.stdout.trim(),stderr:result.stderr.trim()});
const regenerated=await readFile(join(desktop,'build/LICENSE_TR.rtf'));
add('regenerated-ascii-only',[...regenerated].every(byte=>byte<=0x7f));
const regeneratedHash=createHash('sha256').update(regenerated).digest('hex');
add('regenerated-byte-change',regeneratedHash!=='0d781ca2e3cd920e8204f345d62aea6dea06df6b8a2cfbb277b2f9fef604fbc1',regeneratedHash);
await writeFile(join(desktop,'build/LICENSE_TR.rtf'),Buffer.from('{\\rtf1 stale}','ascii'));
result=run('scripts/verify-license-rtf-sync.mjs');
add('rtf-tamper-fails',result.status!==0,result.stderr.trim());
result=run('scripts/generate-license-rtf.mjs');
add('rtf-tamper-repair-pass',result.status===0,result.stdout.trim());
result=run('scripts/verify-license-rtf-sync.mjs');
add('final-sync-pass',result.status===0,result.stderr.trim());
const ok=checks.every(c=>c.status==='PASS');
await mkdir('artifacts/validation',{recursive:true});
await writeFile(report,JSON.stringify({schemaVersion:1,product:'Anadolu Parsı Aile Yaşam Merkezi',applicationVersion:'02.08.2026.225',packageVersion:'2.8.2026-225',build:225,regressionOfBuild:224,purpose:'NSIS license TXT/RTF deterministic synchronization fail-closed runtime',status:ok?'PASS':'FAIL',checks:checks.length,passCount:checks.filter(c=>c.status==='PASS').length,results:checks,generatedAt:new Date().toISOString()},null,2)+'\n');
await rm(temp,{recursive:true,force:true});
console.log(`Build225 Build224 license regression: ${ok?'PASS':'FAIL'} (${checks.filter(c=>c.status==='PASS').length}/${checks.length}).`);
if(!ok){console.error(JSON.stringify(checks.filter(c=>c.status==='FAIL'),null,2));process.exitCode=1;}
