import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { basename, dirname, resolve } from 'node:path';
import { createDependencyHandoffRequest, verifyDependencyHandoffRequest } from './lib/npm-dependency-handoff.mjs';
const args = process.argv.slice(2);
const option = (name, fallback) => { const i = args.indexOf(name); if (i < 0) return fallback; const v = args[i + 1]; if (!v || v.startsWith('--')) throw new Error(`${name} requires a value.`); return v; };
const packageJson = JSON.parse(await readFile('package.json', 'utf8'));
const outputPath = resolve(option('--output', `artifacts/validation/npm-dependency-handoff-request-${packageJson.version}.zip`));
const reportPath = resolve(option('--report', 'artifacts/validation/npm-dependency-handoff-request-creation.json'));
const result = await createDependencyHandoffRequest({ packageName: packageJson.name, packageVersion: packageJson.version, outputPath });
const verification = await verifyDependencyHandoffRequest({ archivePath: outputPath, expectedPackageVersion: packageJson.version, expectedLockBytes: await readFile('package-lock.json') });
const checksumPath = `${outputPath}.sha256`;
await writeFile(checksumPath, `${result.archiveSha256}  ${basename(outputPath)}\n`);
const report = { ...result, verificationStatus: verification.status, checksumPath, product: 'Anadolu Parsı Aile Yaşam Merkezi', stage: 'Bronze RC2 Active Development', generatedAt: new Date().toISOString() };
await mkdir(dirname(reportPath), { recursive: true });
await writeFile(reportPath, `${JSON.stringify(report, null, 2)}\n`);
console.log(`Npm dependency handoff request: ${verification.status} — requestId=${result.requestId} — tarballs=${result.requiredTarballCount}.`);
console.log(`Archive: ${outputPath}\nSHA-256: ${result.archiveSha256}`);
if (verification.status !== 'PASS') process.exitCode = 1;
