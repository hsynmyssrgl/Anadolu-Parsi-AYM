import { readFileSync, existsSync } from 'node:fs';
const checks=[]; const check=(name,value)=>checks.push([name,Boolean(value)]);
const data=readFileSync('apps/desktop/src/main/data-store.ts','utf8');
const app=readFileSync('packages/application/src/audit-write-use-cases.ts','utf8');
const adapter=readFileSync('apps/desktop/src/main/audit-write-application-adapter.ts','utf8');
const repo=readFileSync('packages/repositories/src/audit-repository.ts','utf8');
check('application use-case exists',app.includes('class AppendAuditEntryUseCase'));
check('application port exists',app.includes('interface AuditWriteCommandPort'));
check('sqlite adapter exists',adapter.includes('class RepositoryBackedAuditWriteCommandPort'));
check('adapter uses transaction executor',adapter.includes('transactionExecutor.execute'));
check('adapter delegates repository append',adapter.includes('auditRepository.append'));
check('data store constructs use-case',data.includes('new AppendAuditEntryUseCase'));
check('data store write delegates use-case',data.includes('#appendAuditEntryUseCase.execute'));
const method=data.slice(data.indexOf('#writeAudit('),data.indexOf('\n  }',data.indexOf('#writeAudit('))+4);
check('data store audit method has no SELECT',!method.includes('SELECT sequence_no'));
check('data store audit method has no INSERT',!method.includes('INSERT INTO audit_log'));
check('repository retains chained append',repo.includes('computeAuditEntryHash')&&repo.includes('INSERT INTO audit_log'));
for(const [name,ok] of checks) console.log(`${ok?'PASS':'FAIL'} ${name}`);
const passed=checks.filter(x=>x[1]).length; console.log(`RESULT ${passed}/${checks.length}`); if(passed!==checks.length)process.exit(1);
