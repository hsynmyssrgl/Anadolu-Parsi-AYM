import { ACTIVE_BUILD_META } from './lib/active-build-meta.mjs';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { FamilyDataStore } from '../.tmp/data-store-smoke/data-store.js';
import { createArchivePolicyTestOptions } from './lib/archive-policy-test-harness.mjs';

const root=mkdtempSync(join(tmpdir(),'panthera-mvp56-archive-'));
const databasePath=join(root,'family.db');
const archivePath=join(root,'archive');
const sourcePath=join(root,'vasiyet.pdf');
const bytes=Buffer.from('%PDF-1.7\nPanthera archive verification\n','utf8');
writeFileSync(sourcePath,bytes);
const checks=[]; const check=(name,fn)=>{fn();checks.push(name)};
const policyOptions=createArchivePolicyTestOptions();
let store;
try{
  store=new FamilyDataStore({databasePath,archivePath,applicationVersion:ACTIVE_BUILD_META.applicationVersion,migrationBackupDirectory:join(root,'migration-backups'),...policyOptions});
  store.setupAdmin({displayName:'Arşiv Yöneticisi',email:'archive@example.com',password:'GucluArsivParolasi!2026'});
  const linkedEvent=(await store.createEvent({title:'Arşiv doğrulama etkinliği',startAt:'2026-08-06T09:00:00.000Z',visibility:'family',participantPersonIds:(await store.getSnapshot()).people.map(person=>person.id),aiProcessingAllowed:false})).event;
  assert.ok(linkedEvent);
  const initialAttachmentCount=linkedEvent.attachmentCount;
  check('fresh database applies migration 11',()=>assert.equal(store.getSystemHealth().integrityOk,true));
  const beforeFiles=existsSync(archivePath)?readdirSync(archivePath).length:0;
  const imported=await store.importArchiveFile(sourcePath,{title:'Aile Vasiyet Belgesi',linkedEventId:linkedEvent.id});
  check('archive item imported through application use case',()=>assert.equal(imported.length,1));
  const item=imported[0];
  check('archive metadata preserved',()=>{assert.equal(item.title,'Aile Vasiyet Belgesi');assert.equal(item.originalName,'vasiyet.pdf');assert.equal(item.mimeType,'application/pdf');assert.equal(item.sizeBytes,bytes.length);});
  check('sha256 is authoritative',()=>assert.equal(item.sha256,createHash('sha256').update(bytes).digest('hex')));
  check('encrypted vault file created',()=>assert.equal(readdirSync(archivePath).length,beforeFiles+1));
  const opened=await store.openArchiveItem(item.id);
  check('encrypted item opens with identical bytes',()=>assert.deepEqual(readFileSync(opened),bytes));
  const versions=store.listArchiveVersions(item.id);
  check('initial immutable version recorded',()=>{assert.equal(versions.length,1);assert.equal(versions[0].versionNo,1);assert.equal(versions[0].sha256,item.sha256);});
  check('linked event attachment count increments transactionally',()=>{const db=new DatabaseSync(databasePath,{readOnly:true});try{assert.equal(Number(db.prepare('SELECT attachment_count c FROM events WHERE id=?').get(linkedEvent.id).c),initialAttachmentCount+1);}finally{db.close();}});
  check('archive audit evidence exists',()=>assert.ok(store.listAudit(100).some(x=>x.action==='archive.imported'&&x.resourceId===item.id)));
  check('archive outbox evidence exists',()=>{const db=new DatabaseSync(databasePath,{readOnly:true});try{assert.equal(Number(db.prepare("SELECT count(*) c FROM event_outbox WHERE event_type='archive.item.imported' AND aggregate_id=?").get(item.id).c),1);}finally{db.close();}});
  check('archive list delegates to repository query',()=>assert.equal(store.listArchive()[0].id,item.id));
  const filesBeforeFailure=readdirSync(archivePath).length;
  await assert.rejects(()=>store.importArchiveFile(sourcePath,{title:'Geçersiz Bağlantı',linkedEventId:'missing-event'}),/RESOURCE-CONFLICT-001/);
  check('invalid linked event rolls back metadata',()=>assert.equal(store.listArchive().length,1));
  check('failed import removes orphan vault file',()=>assert.equal(readdirSync(archivePath).length,filesBeforeFailure));
  check('audit chain remains valid',()=>assert.equal(store.verifyAuditIntegrity().valid,true));
  store.close(); store=undefined;
  const reopened=new FamilyDataStore({databasePath,archivePath,applicationVersion:ACTIVE_BUILD_META.applicationVersion,...policyOptions});
  reopened.login({email:'archive@example.com',password:'GucluArsivParolasi!2026'});
  check('archive survives application restart',()=>assert.equal(reopened.listArchive().length,1));
  check('version stored_name survives migration and restart',()=>{const db=new DatabaseSync(databasePath,{readOnly:true});try{assert.ok(String(db.prepare('SELECT stored_name FROM archive_versions WHERE archive_item_id=?').get(item.id).stored_name).endsWith('.vault'));}finally{db.close();}});
  reopened.close();
  const report={schemaVersion:1,product:'Panthera pardus tulliana',version:ACTIVE_BUILD_META.applicationVersion,milestone:ACTIVE_BUILD_META.milestone,status:'passed',checks:checks.length,scenarios:checks,sha256:item.sha256,generatedAt:new Date().toISOString()};
  writeFileSync('artifacts/manifests/ARCHIVE_USE_CASE_VERIFICATION_MVP56.json',JSON.stringify(report,null,2)+'\n');
  console.log(JSON.stringify(report,null,2));
}finally{store?.close();rmSync(root,{recursive:true,force:true});}
